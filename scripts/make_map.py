#!/usr/bin/env python3
"""Build js/land.js from Natural Earth's 1:110m land (the world-atlas TopoJSON build,
public domain data): the coastlines as rings of [lon, lat] in tenths of a degree, and
a 1° land mask for placing stations.

    curl -o land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json
    python3 scripts/make_map.py land-110m.json
"""
import base64
import json
import sys
from pathlib import Path

topo = json.loads(Path(sys.argv[1]).read_text())
sx, sy = topo['transform']['scale']
tx, ty = topo['transform']['translate']

# Decode the delta-encoded, quantised arcs.
arcs = []
for arc in topo['arcs']:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx
        y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)


def ring(indices):
    out = []
    for i in indices:
        pts = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(pts if not out else pts[1:])
    return out


def unwrap(r):
    """Make longitudes continuous across the date line (Fiji, Chukotka), so a ring that
    crosses it runs past ±180 instead of jumping across the whole map."""
    out = [r[0]]
    for x, y in r[1:]:
        px = out[-1][0]
        while x - px > 180:
            x -= 360
        while x - px < -180:
            x += 360
        out.append((x, y))
    return out


rings = []
for geom in topo['objects']['land']['geometries']:
    polys = geom['arcs'] if geom['type'] == 'MultiPolygon' else [geom['arcs']]
    for poly in polys:
        for r in poly:
            rings.append(unwrap(ring(r)))

# A ring that runs past ±180 is also needed shifted a full turn, for the mask.
copies = []
for r in rings:
    copies.append(r)
    if max(x for x, _ in r) > 180:
        copies.append([(x - 360, y) for x, y in r])
    if min(x for x, _ in r) < -180:
        copies.append([(x + 360, y) for x, y in r])

# Even-odd scanline fill at each 1° cell centre.
W, H = 360, 180
bits = bytearray(W * H // 8)
for row in range(H):
    lat = 90 - row - 0.5
    xs = []
    for r in copies:
        for (x0, y0), (x1, y1) in zip(r, r[1:] + r[:1]):
            if (y0 > lat) != (y1 > lat):
                xs.append(x0 + (lat - y0) * (x1 - x0) / (y1 - y0))
    xs.sort()
    for a, b in zip(xs[0::2], xs[1::2]):
        for col in range(W):
            lon = -180 + col + 0.5
            if a <= lon < b:
                i = row * W + col
                bits[i >> 3] |= 1 << (i & 7)

flat = [[round(v * 10) for p in r for v in p] for r in rings if len(r) > 2]
land = sum(bin(b).count('1') for b in bits) / (W * H)
out = Path(__file__).resolve().parent.parent / 'js' / 'land.js'
out.write_text(
    '// Generated by scripts/make_map.py from Natural Earth 1:110m land (public domain).\n'
    '// LAND: coastline rings, flat [lon, lat, lon, lat, …] in tenths of a degree. Rings that\n'
    '// cross the date line run past ±180°, so draw those twice, a full turn apart.\n'
    '// MASK: 360×180 bits, row 0 at 90°N, column 0 at 180°W, 1 = land.\n'
    f'export const LAND = {json.dumps(flat, separators=(",", ":"))};\n'
    f"export const MASK = '{base64.b64encode(bytes(bits)).decode()}';\n")
print(f'{len(flat)} rings, {sum(len(r) for r in flat) // 2} points, {land:.1%} land, {out.stat().st_size // 1024} KB')
